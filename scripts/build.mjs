import {readFileSync,writeFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const {version}=JSON.parse(readFileSync(new URL('package.json',root),'utf8'));
const modules=['policy.mjs','controller.mjs','addons.sys.mjs','ui.mjs','runtime.sys.mjs'];
const body=modules.map(name=>`// ---- src/${name} ----\n`+readFileSync(new URL('src/'+name,root),'utf8').replace(/^import .* from ['"]\.\/.*['"];\n/gm,'')).join('\n');
writeFileSync(new URL(`manager-${version}.sys.mjs`,root),'// Generated by scripts/build.mjs; edit src/ instead.\n'+body);
writeFileSync(new URL('bootstrap.uc.js',root),readFileSync(new URL('src/bootstrap.uc.js',root),'utf8').replace('src/runtime.sys.mjs',`manager-${version}.sys.mjs`));
